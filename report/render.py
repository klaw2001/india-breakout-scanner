def esc(s):
    return html.escape(str(s)) if s is not None else ""


def pct(x, signed=True):
    if x is None:
        return "–"
    s = f"{x:+.2f}%" if signed else f"{x:.2f}%"
    return s.replace("-", "−")


def result_cell(r, cache):
    if r.get("index"):
        return '<td class="res mut">n/a (index)</td>'
    e = cache.get(r["symbol"])
    if not e or e.get("verdict") == "NA":
        why = "no result found" if e else "not checked yet"
        return f'<td class="res mut"><i>Pending</i> · {why}</td>'
    cls = {"Good": "good", "In-line": "inl", "Bad": "bad"}[e["verdict"]]
    col = {"good": "g", "inl": "o", "bad": "r"}[cls]
    return (f'<td class="res {cls}"><span class="dot {cls}"></span><b class="{col}">{esc(e["verdict"])}</b> '
            f'<span class="mut">{esc(e["quarter"])}</span><br>{esc(e["text"])}</td>')


def tf_cell(r, longterm):
    parts = []
    specs = [("M", r.get("m"))] if longterm else [("W", r.get("w")), ("M", r.get("m"))]
    for lab, st in specs:
        if not st:
            parts.append(f'<b class="mut">{lab} n/a</b>')
            continue
        cls, word = ("g", "above") if st["above"] else ("o", "below")
        parts.append(f'<b class="{cls}">{lab} {word}</b><br>({indian(st["level"])})')
    if longterm and r.get("hi52_pct") is not None:
        cls = "g" if r["hi52_pct"] >= -5 else "mut"
        parts.append(f'<b class="{cls}">52w hi {pct(r["hi52_pct"])}</b><br>({indian(r["hi52"])})')
    return '<td class="tf">' + "<br>".join(parts) + "</td>"


def vol_cell(r, scan, vol_min):
    if r.get("index"):
        return '<td class="n mut">n/a</td>'
    vr = r.get("vol_ratio")
    if vr is None:
        top = '<span class="mut">–</span>'
    elif vr >= vol_min:
        top = f'<b class="g">{vr:.1f}× ✓</b>'
    else:
        top = f'<b class="o">{vr:.1f}×</b>'
    lines = [top]
    if r.get("days"):
        lines.append('<span class="small">on breakout bar</span>')
    if scan == "swing" and r.get("deliv") is not None:
        lines.append(f'<span class="small">Del {r["deliv"]:.0f}%</span>')
    if scan == "intraday" and r.get("v15_trigger"):
        lines.append(f'<span class="small">15m ≥ {shares(r["v15_trigger"])}</span>')
    return '<td class="n">' + "".join(lines) + "</td>"


def row_html(r, scan, cfg_params, cache):
    above = r["group"] == "above"
    dcls = "g" if above else "o"
    days = ""
    if r.get("days"):
        days = f'<span class="small">day {r["days"]}</span>'
    lvl = f'{indian(r["level"])}'
    if scan == "intraday" and above and r.get("trigger") and r["trigger"] != r["level"]:
        lvl += f'<span class="small">trigger PDH {indian(r["trigger"])}</span>'
    if scan == "intraday":
        risk_cells = f'<td class="n">{indian(r.get("stop"))}</td><td class="n">{indian(r.get("target"))}</td>'
    else:
        risk_cells = f'<td class="n">{indian(r.get("inv"))}</td><td class="n">{indian(r.get("target"))}</td>'
    return (
        "<tr>"
        f'<td class="name"><b>{esc(r["name"])}</b><span>{esc(r["code"])}</span></td>'
        f'<td class="n">{indian(r["close"])}</td>'
        f'<td class="n">{lvl}</td>'
        f'<td class="n"><b class="{dcls}">{pct(r["diff"])}</b>{days}</td>'
        f"{risk_cells}"
        f'{vol_cell(r, scan, cfg_params.get("vol_min", 1.5))}'
        f'{tf_cell(r, scan == "longterm")}'
        f"{result_cell(r, cache)}"
        "</tr>"
    )


def header_html(scan, tfw):
    lvl = "Weekly breakout" if scan == "longterm" else ("Breakout" if scan == "intraday" else "Daily breakout")
    risk = "Stop" if scan == "intraday" else "Invalidation"
    vol = "Volume (wk)" if scan == "longterm" else "Volume"
    tf = "Monthly / 52w" if scan == "longterm" else "Weekly / monthly"
    cols = ["Name", "Close", lvl, "vs breakout", risk, "Target", vol, tf, "Latest quarterly result"]
    return "<thead><tr>" + "".join(f"<th>{c}</th>" for c in cols) + "</tr></thead>"


def global_box(meta):
    g = meta.get("global") or []
    if not g:
        return ""
    rows = []
    for x in g:
        if x["close"] is None:
            rows.append(f'<tr><td>{esc(x["label"])}</td><td class="n mut" colspan="3">no data</td></tr>')
            continue
        cls = "g" if (x["chg"] or 0) >= 0 else "r"
        if x["ticker"] in ("^VIX", "INR=X"):     # rising VIX / rupee weakness is a negative for India
            cls = "r" if (x["chg"] or 0) > 0 else "g"
        rows.append(f'<tr><td>{esc(x["label"])}</td><td class="n">{indian(x["close"])}</td>'
                    f'<td class="n"><b class="{cls}">{pct(x["chg"])}</b></td><td class="n mut">{esc(x["date"])}</td></tr>')
    by = {x["ticker"]: x for x in g}
    spx, inda = (by.get("^GSPC") or {}).get("chg"), (by.get("INDA") or {}).get("chg")
    read = ""
    if spx is not None and inda is not None:
        avg = (spx + inda) / 2
        bias = ("positive" if avg > 0.3 else "negative" if avg < -0.3 else "flat")
        bcls = {"positive": "g", "negative": "r", "flat": "o"}[bias]
        read = (f'<p>Overnight read (mechanical: average of S&amp;P 500 and INDA moves): '
                f'<b class="{bcls}">{bias} bias for the open</b>. Gap-ups above a breakout need the first '
                f'15-minute candle to close above it on volume before entry.</p>')
    return ('<h2>Overnight markets (US close → India open)</h2>'
            '<table class="glob"><thead><tr><th>Market</th><th>Close</th><th>Change</th><th>Date</th></tr></thead>'
            + "".join(rows) + "</table>" + read)


def build_html(doc, cache):
    meta, rows = doc["meta"], doc["rows"]
    scan, p = meta["scan"], meta["params"]
    tfw = p.get("tf_word", "daily")
    b1, b2 = p["bands"]
    counts = meta["counts"]
    groups = {g: [r for r in rows if r["group"] == g] for g in GROUP_ORDER}
    tf_noun = "weekly" if scan == "longterm" else "daily"
    titles = {
        "above": f"Closed above the {tf_noun} breakout",
        "on": f"Closed on the {tf_noun} breakout",
        "near1": f"Within {b1:g}% below",
        "near2": f"{b1:g}–{b2:g}% below",
    }
    sess = meta["session_label"]
    uni = UNIVERSE_LABEL[meta["universe"]].format(t=p.get("min_turnover_cr", 5))
    n_names = meta["scanned"]
    close_word = "week" if scan == "longterm" else "session"

    # ---------- summary ----------
    stocks_flagged = [r for r in rows if not r.get("index")]
    ab = groups["above"]
    vol_ok = sum(1 for r in ab if r.get("vol_ok"))
    ab_stocks = sum(1 for r in ab if not r.get("index"))
    li = [f'<li><b class="g">{len(ab)} closed above</b> the {tf_noun} breakout'
          + (f' — <b class="g">{vol_ok} of {ab_stocks}</b> stocks on ≥{p["vol_min"]:g}× volume.' if ab_stocks else ".")
          + "</li>"]
    on = groups["on"]
    if len(on) == 1:
        li.append(f'<li><b class="o">1 closed on</b> it ({esc(on[0]["name"])} {indian(on[0]["close"])}).</li>')
    else:
        li.append(f'<li><b class="o">{len(on)} closed on</b> it.</li>')
    li.append(f'<li><b class="o">{len(groups["near1"])} within {b1:g}% below</b>.</li>')
    li.append(f'<li><b class="o">{len(groups["near2"])} {b1:g}–{b2:g}% below</b>.</li>')
    li.append(f'<li>{counts["far"]} more than {b2:g}% below and {counts["extended"]} more than '
              f'{p["max_ext"]:g}% above (extended): not listed.</li>')
    if scan == "longterm":
        m_above = sum(1 for r in rows if (r.get("m") or {}).get("above"))
        near_hi = sum(1 for r in rows if r.get("hi52_pct") is not None and r["hi52_pct"] >= -5)
        li.append(f"<li><b>Monthly / 52-week:</b> {m_above} of {len(rows)} flagged above the monthly breakout; "
                  f"{near_hi} within 5% of the 52-week high.</li>")
    else:
        w_above = sum(1 for r in rows if (r.get("w") or {}).get("above"))
        both = sum(1 for r in rows if (r.get("w") or {}).get("above") and (r.get("m") or {}).get("above"))
        li.append(f"<li><b>Weekly / monthly:</b> {w_above} of {len(rows)} flagged above weekly breakout; "
                  f"{both} above both.</li>")
    verdicts = [cache.get(r["symbol"], {}).get("verdict") for r in stocks_flagged]
    good, inl, bad = verdicts.count("Good"), verdicts.count("In-line"), verdicts.count("Bad")
    pend = len(stocks_flagged) - good - inl - bad
    li.append(f'<li><b>Results:</b> <b class="g">{good} Good</b>, <b class="o">{inl} In-line</b>, '
              f'<b class="r">{bad} Bad</b> across {len(stocks_flagged)} flagged stocks'
              + (f" ({pend} pending)." if pend else ".") + "</li>")

    checked = sorted({cache[r["symbol"]]["checked"] for r in stocks_flagged if r["symbol"] in cache})
    last_checked = checked[-1] if checked else "never"
    price_src = ("official NSE closes and volumes for " + sess + " (NSE full bhavcopy"
                 + (", with delivery %" if scan == "swing" else "") + "); price history and indices from Yahoo Finance."
                 if meta.get("bhavcopy") else
                 "Yahoo Finance closes for " + sess + " (NSE bhavcopy was unavailable for this run).")
    if scan == "intraday":
        price_src += " Overnight markets from Yahoo Finance."
    prices_p = (f"<p><b>Prices:</b> {price_src} Universe: {meta['universe_size']} {uni} plus "
                f"{meta['indices']} indices; {n_names} had a {close_word} close on {meta['session_date']}"
                + (f", {meta['illiquid']} skipped below the turnover cut-off" if meta.get("illiquid") else "")
                + f". Results column from the results cache, last checked {last_checked}. "
                  "Colour: green above, orange on/below; result verdicts green good, orange in-line, red bad.</p>")

    sub_bits = {"intraday": f"Pre-market watchlist for the session after {sess}",
                "swing": f"{sess} session close", "longterm": f"Week ending {sess}"}
    out = [f"<h1>{esc(meta['title'])}</h1>",
           f'<p class="sub">{sub_bits[scan]} · {n_names} names scanned ({uni}) · groups listed A to Z</p>',
           f'<div class="summary"><p class="sh">{sess} close vs {tf_noun} breakout</p><ul>{"".join(li)}</ul></div>',
           prices_p]
    if scan == "intraday":
        out.append(global_box(meta))

    n = 0
    for g in GROUP_ORDER:
        rs = groups[g]
        if not rs:
            continue
        n += 1
        out.append(f"<h2>{n}. {titles[g]} ({len(rs)})</h2>")
        out.append('<p class="lead">Listed alphabetically by company name, A to Z.</p>')
        out.append("<table>" + header_html(scan, tfw) + "<tbody>"
                   + "".join(row_html(r, scan, p, cache) for r in rs) + "</tbody></table>")
    if n == 0:
        out.append("<p><b>No stocks are on or within the listed bands of a breakout this time.</b></p>")

    out.append('<p class="note">' + method_note(scan, p) + "</p>")
    return out, sess


def method_note(scan, p):
    l, r = p["pivot"]
    bar = "week" if scan == "longterm" else "day"
    s = (f"<b>Method.</b> Breakout = the swing high (highest of {l} {bar}s before and {r} after) that price "
         f"broke within the last {p['recent']} {bar}s and still holds, otherwise the nearest untaken swing high "
         f"above price, searched over {p['lookback']} {bar}s. ")
    if scan == "intraday":
        s += (f"Trigger = breakout, or the previous day's high (PDH) for stocks already above it. Stop = trigger − "
              f"{p['atr_stop']:g}× ATR(14); target = trigger + {p['atr_target']:g}× ATR(14), a 2R plan. "
              f"Volume = last session vs its {p['vol_avg']}-day average; 15m ≥ shows the volume a 15-minute "
              f"breakout candle needs ({p['vol_min']:g}× the 10-session average candle, opening candle excluded). ")
    else:
        s += (f"Invalidation = most recent swing low below the breakout. Target = breakout + "
              f"{p['r_multiple']:g}× (breakout − invalidation). Volume = breakout {bar} (or latest {bar}) vs the "
              f"previous {p['vol_avg']}-{bar} average; ✓ = at least {p['vol_min']:g}×. ")
        if scan == "swing":
            s += "Del = NSE delivery % for the session. "
    s += ("Results verdicts (consolidated, YoY): Good = PAT +15% or more, or back to profit; Bad = PAT down, "
          "a loss, or a wider loss; In-line = in between. Scanner output, not investment advice.")
    return s


def render(scan, out=None):
    from weasyprint import CSS as WCSS, HTML
    from weasyprint.text.fonts import FontConfiguration

    doc = load_scan(scan)
    cache = load_cache()
    body, sess = build_html(doc, cache)
    css = CSS % {"title": doc["meta"]["title"].replace('"', ""), "sess": sess,
                 "fonts": (ROOT / "fonts").as_uri()}
    page = f"<html><head><meta charset='utf-8'><title>{esc(doc['meta']['title'])} {esc(sess)}</title></head>" \
           f"<body>{''.join(body)}</body></html>"
    if out is None:
        name = {"intraday": "Intraday", "swing": "Swing", "longterm": "LongTerm"}[scan]
        out = ROOT / "reports" / scan / f"India_{name}_Breakout_Scan_{doc['meta']['session_date']}.pdf"
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    fc = FontConfiguration()
    HTML(string=page, base_url=str(ROOT)).write_pdf(
        str(out), stylesheets=[WCSS(string=css, base_url=str(ROOT), font_config=fc)], font_config=fc)
    return out


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--scan", required=True, choices=["intraday", "swing", "longterm"])
    ap.add_argument("--out")
    a = ap.parse_args(argv)
    print(render(a.scan, a.out))


if __name__ == "__main__":
    main()
